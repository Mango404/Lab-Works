def count_letters(text):
    """
    Подсчитывает количество каждой буквы в тексте.

    Аргументы:
    text (str): текст для анализа

    Возвращает:
    dict: словарь с буквами в нижнем регистре и их количеством
    """
    letters_count = {}

    for char in text:
        # Проверяем, является ли символ буквой
        if char.isalpha():
            # Приводим к нижнему регистру и увеличиваем счетчик
            char_lower = char.lower()
            if char_lower in letters_count:
                letters_count[char_lower] += 1
            else:
                letters_count[char_lower] = 1

    return letters_count


def calculate_frequency(letters_dict):
    """
    Вычисляет частоту каждой буквы.

    Аргументы:
    letters_dict (dict): словарь с буквами и их количеством

    Возвращает:
    dict: словарь с буквами и их частотой
    """
    # Вычисляем общее количество букв
    total_letters = 0
    for count in letters_dict.values():
        total_letters += count

    # Создаем словарь с частотами
    frequency_dict = {}

    for letter, count in letters_dict.items():
        # Вычисляем частоту: количество буквы / общее количество букв
        frequency = count / total_letters
        frequency_dict[letter] = frequency

    return frequency_dict


main_str = """
У лукоморья дуб зелёный;
Златая цепь на дубе том:
И днём и ночью кот учёный
Всё ходит по цепи кругом;
Идёт направо — песнь заводит,
Налево — сказку говорит.
Там чудеса: там леший бродит,
Русалка на ветвях сидит;
Там на неведомых дорожках
Следы невиданных зверей;
Избушка там на курьих ножках
Стоит без окон, без дверей;
Там лес и дол видений полны;
Там о заре прихлынут волны
На брег песчаный и пустой,
И тридцать витязей прекрасных
Чредой из вод выходят ясных,
И с ними дядька их морской;
Там королевич мимоходом
Пленяет грозного царя;
Там в облаках перед народом
Через леса, через моря
Колдун несёт богатыря;
В темнице там царевна тужит,
А бурый волк ей верно служит;
Там ступа с Бабою Ягой
Идёт, бредёт сама собой,
Там царь Кащей над златом чахнет;
Там русский дух… там Русью пахнет!
И там я был, и мёд я пил;
У моря видел дуб зелёный;
Под ним сидел, и кот учёный
Свои мне сказки говорил.
"""
letters_count = count_letters(main_str)

# Вычисление частот
frequency_dict = calculate_frequency(letters_count)

# Распечатка в столбик
for letter, frequency in sorted(frequency_dict.items()):
    print(f"{letter}: {frequency:.2f}")
